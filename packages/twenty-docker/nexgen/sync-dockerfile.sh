#!/usr/bin/env bash
# Regenerates ./Dockerfile from ../twenty/Dockerfile, keeping only the stages the
# production `twenty` image needs. Railway always builds the last stage and has no
# --target option, so the upstream file (whose last stage is twenty-app-dev) can't be used.
# Run after merging a Twenty release: bash packages/twenty-docker/nexgen/sync-dockerfile.sh
set -euo pipefail

directory="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

{
  echo "# GENERATED by sync-dockerfile.sh from ../twenty/Dockerfile. Do not edit by hand."
  echo
  awk '
    /^FROM / { skip = ($NF ~ /^(twenty-server-aws|twenty-aws|s6-fetch|clickhouse|twenty-app-dev)$/) }
    !skip
  ' "$directory/../twenty/Dockerfile"
} > "$directory/Dockerfile"

grep -q '^FROM twenty-server AS twenty$' "$directory/Dockerfile"
echo "Wrote $directory/Dockerfile (last stage: $(grep '^FROM ' "$directory/Dockerfile" | tail -1))"
